#[derive(Default)]
struct Screen {
    root: String,
    initializers: Vec<String>,
    actions: Vec<(String, String)>,
    limitations: Vec<String>,
}

impl Screen {
    fn action(&mut self, statement: String) -> String {
        let id = format!("rewrite-{}", self.actions.len() + 1);
        self.actions.push((id.clone(), statement));
        quote(&id)
    }

    fn kotlin(&self) -> String {
        let initializers = self.initializers.join("\n        ");
        let actions = self
            .actions
            .iter()
            .map(|(id, statement)| format!("            {} -> {statement}", quote(id)))
            .collect::<Vec<_>>()
            .join("\n");
        let handlers = if actions.is_empty() {
            String::new()
        } else {
            format!(
                "\n    override fun handleAction(action: String, payload: String?) {{\n        when (action) {{\n{actions}\n        }}\n    }}\n"
            )
        };
        let root = self.root.lines().collect::<Vec<_>>().join("\n        ");
        format!(
            "// Generated by feather-cli rewrite.\nimport dev.feather.sdk.*\n\nclass MigratedApp : FeatherApp() {{\n    override fun onCreate() {{\n        {initializers}\n    }}\n\n    override fun render(): Widget = {}\n{handlers}}}\n\nfun main() = installApp(MigratedApp())\n",
            root
        )
    }
}

fn group(name: &str, children: Vec<String>, style: &str) -> String {
    if children.is_empty() {
        return format!("{name}(listOf(){style})");
    }
    let children = children
        .into_iter()
        .map(|child| format!("    {},", child.lines().collect::<Vec<_>>().join("\n    ")))
        .collect::<Vec<_>>()
        .join("\n");
    format!("{name}(listOf(\n{children}\n){style})")
}

fn quote(value: &str) -> String {
    let mut text = String::from("\"");
    for ch in value.chars() {
        match ch {
            '"' | '\\' | '$' => {
                text.push('\\');
                text.push(ch);
            }
            '\n' => text.push_str("\\n"),
            '\r' => text.push_str("\\r"),
            '\t' => text.push_str("\\t"),
            ch if ch.is_control() => text.push_str(&format!("\\u{:04x}", ch as u32)),
            ch => text.push(ch),
        }
    }
    text.push('"');
    text
}

pub fn run(
    source: PathBuf,
    entry: Option<PathBuf>,
    component: Option<String>,
    output: PathBuf,
    refresh: bool,
) -> Result<(), Box<dyn Error>> {
    let source = source.canonicalize()?;
    let entry = if source.is_dir() {
        let path = if let Some(entry) = entry {
            source.join(entry)
        } else {
            let entries = ["App.tsx", "App.jsx", "App.js"].into_iter()
                .map(|file| source.join(file)).filter(|file| file.is_file()).collect::<Vec<_>>();
            let [path] = entries.as_slice() else {
                return Err("Specify --entry when the project does not have exactly one default React Native entry".into());
            };
            path.clone()
        }.canonicalize()?;
        if !path.starts_with(&source) {
            return Err("Entry must be inside the source project".into());
        }
        path
    } else {
        if entry.is_some() {
            return Err("--entry requires a source directory".into());
        }
        source.clone()
    };
    let parent = output
        .parent()
        .filter(|path| !path.as_os_str().is_empty())
        .unwrap_or_else(|| Path::new("."))
        .canonicalize()?;
    let output = parent.join(
        output
            .file_name()
            .ok_or("Output must name a project directory")?,
    );
    if output == source || (source.is_dir() && output.starts_with(&source)) {
        return Err("Choose an output directory outside the source project".into());
    }
    if fs::symlink_metadata(&output).is_ok_and(|info| info.is_symlink()) {
        return Err("Output must be a project directory, not a symbolic link".into());
    }
    let input = fs::read_to_string(&entry)?;
    if component.is_some() && entry.extension().and_then(|ext| ext.to_str()) == Some("xml") {
        return Err("An Android XML file is already a single layout; omit --component".into());
    }
    let (adapter, screen) = match entry.extension().and_then(|ext| ext.to_str()) {
        Some("tsx" | "jsx" | "js" | "ts") => ("react-native", react_native::translate(&input, component.as_deref())?),
        Some("xml") => ("android-layout", android::translate(&input)?),
        Some("kt") => ("compose", compose::translate(&input, component.as_deref().ok_or("Specify --component with the Compose function name")?)?),
        Some("java") => return Err("Choose an Android res/layout XML file with --entry. Java controllers and programmatic views require manual migration.".into()),
        _ => return Err("Expected React Native JSX/TSX, Compose Kotlin, or Android XML".into()),
    };
    let lock = if refresh {
        let lock = fs::File::options()
            .create(true)
            .truncate(false)
            .read(true)
            .write(true)
            .open(output.join(".rewrite.lock"))?;
        lock.lock()?;
        let previous: serde_json::Value =
            serde_json::from_slice(&fs::read(output.join("migration-report.json"))?)?;
        let current = fs::read(output.join("App.kt"))?;
        if previous["generated_sha256"] != artifact_for("App.kt", &current).sha256
            || previous["source"] != serde_json::to_value(&entry)?
        {
            return Err("Refresh requires the same source and an unedited generated App.kt".into());
        }
        let manifest: serde_json::Value =
            serde_json::from_slice(&fs::read(output.join("feather.json"))?)?;
        if manifest["entry"] != "App.kt" || manifest["runtime"] != "kotlin-js" {
            return Err("Refresh requires the generated Kotlin/JS entry in feather.json".into());
        }
        Some((lock, current, manifest))
    } else {
        if output.exists() {
            return Err(
                "Output already exists; use --refresh for an unedited generated project".into(),
            );
        }
        None
    };
    let stage = parent.join(format!(
        ".feather-rewrite-{}-{}",
        std::process::id(),
        SystemTime::now().duration_since(UNIX_EPOCH)?.as_nanos()
    ));
    fs::create_dir(&stage)?;
    let result = (|| -> Result<(), Box<dyn Error>> {
        let kotlin = screen.kotlin();
        let default_manifest = serde_json::json!({"entry":"App.kt","runtime":"kotlin-js","sdkVersion":crate::constants::FEATHER_SDK_VERSION});
        let manifest = lock
            .as_ref()
            .map(|(_, _, manifest)| manifest)
            .unwrap_or(&default_manifest);
        fs::write(stage.join("App.kt"), &kotlin)?;
        fs::write(
            stage.join("feather.json"),
            serde_json::to_vec_pretty(&manifest)?,
        )?;
        let report = serde_json::json!({
            "source": entry,
            "adapter": adapter,
            "component": component,
            "generated_sha256": artifact_for("App.kt", kotlin.as_bytes()).sha256,
            "limitations": screen.limitations
        });
        fs::File::create_new(stage.join("migration-report.json"))?
            .write_all(&serde_json::to_vec_pretty(&report)?)?;
        crate::compiler::compile_javascript(&stage)?;
        let engine = feather_core::AppRuntime::new();
        engine.load_javascript(fs::read_to_string(stage.join(".feather/app.js"))?)?;
        engine.render_javascript()?;
        if let Some((_, current, _)) = &lock {
            // The running server owns .feather and observes this atomic source replacement.
            if fs::read(output.join("App.kt"))? != *current {
                return Err("App.kt changed while the rewrite was being verified".into());
            }
            if current != kotlin.as_bytes() {
                fs::rename(stage.join("App.kt"), output.join("App.kt"))?;
            }
            fs::rename(
                stage.join("migration-report.json"),
                output.join("migration-report.json"),
            )?;
        } else {
            if output.exists() {
                return Err("Output was created during the rewrite".into());
            }
            fs::remove_dir_all(stage.join(".feather"))?;
            fs::rename(&stage, &output)?;
        }
        for item in &screen.limitations {
            eprintln!("Rewrite: {item}");
        }
        println!("Verified Feather project: {}", output.display());
        Ok(())
    })();
    if stage.exists() {
        let _ = fs::remove_dir_all(stage);
    }
    result
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn native_jsx_generates_state_and_marks_unsupported_logic() {
        let source = r#"
            import {useState} from "react";
            import {View, Text as Label, Button, TextInput} from "react-native";
            import {Label as Custom} from "my-ui";
            function App() {
                const [count, setCount] = useState(0);
                const [name, setName] = useState("Amina");
                return <View>
                    <Label>{name}: {count}</Label>
                    <Button title="Add" onPress={() => setCount(count + 1)} />
                    <TextInput value={name} onChangeText={setName} />
                    <Custom value={count} />
                </View>;
            }
        "#;
        let result = react_native::translate(source, Some("App")).unwrap();
        assert_eq!(result.actions.len(), 2);
        assert!(result.actions[0].1.contains("+ 1L"));
        assert!(result.actions[1].1.contains("actionText(payload)"));
        assert!(result.root.contains("getState(\"rewrite-state:count\")"));
        assert!(
            result
                .limitations
                .iter()
                .any(|message| message.contains("Component Custom"))
        );
    }

    #[test]
    fn react_native_preserves_literal_list_content_and_local_feature_props() {
        let source = r#"
            import {View, Text, Image, Pressable} from "react-native";
            import {Music} from "lucide-react-native";
            const UPDATES = [
                {title: "First", image: "https://example.com/one.png"},
                {title: "Second", image: "https://example.com/two.png"},
            ];
            const Feature = ({label, icon}: any) => <View>{icon}<Text>{label}</Text></View>;
            function Screen() {
                return <View>
                    {UPDATES.map((item) => (
                        <Pressable onPress={external}>
                            <Image source={{uri: item.image}}/>
                            <Text>{item.title}</Text>
                        </Pressable>
                    ))}
                    <Feature label="Mix" icon={<Music/>}/>
                </View>;
            }
        "#;
        let screen = react_native::translate(source, Some("Screen")).unwrap();
        for label in ["First", "Second", "Mix"] {
            assert!(screen.root.contains(&format!("Text(\"{label}\")")));
        }
        assert!(
            screen
                .root
                .contains("Image(\"https://example.com/two.png\"")
        );
        assert!(screen.root.contains("Icon(\"music\")"));
        assert!(!screen.root.contains("[dynamic value]"));
        assert!(!screen.root.contains("Unsupported component"));
        assert!(
            screen
                .limitations
                .iter()
                .any(|note| note.contains("handler requires manual migration"))
        );
    }

    #[test]
    fn react_native_keeps_main_screen_header_and_translates_alpha_colors() {
        let source = r##"
            import {Pressable, Text, View} from "react-native";
            import {ArrowLeft} from "lucide-react-native";
            import Motion, {useAnimatedStyle} from "react-native-reanimated";
            function Screen() {
                if (loading) return <Text>Loading</Text>;
                return <View style={{backgroundColor: "#234f"}}>
                    <View style={{flexDirection: "row"}}>
                        <Pressable onPress={goBack}><ArrowLeft color="#fff"/></Pressable>
                        <Text style={{color: "rgba(255,255,255,0.6)"}}>Heading</Text>
                    </View>
                    <Motion.ScrollView><Text>Body</Text></Motion.ScrollView>
                </View>;
            }
        "##;
        let screen = react_native::translate(source, Some("Screen")).unwrap();
        assert!(screen.root.contains("Heading"));
        assert!(!screen.root.contains("Loading"));
        assert!(screen.root.contains("fillMaxHeight = true"));
        assert!(screen.root.contains("width = \"40\""));
        assert!(screen.root.contains("Icon(\"back\", color = \"#ffffff\")"));
        assert!(screen.root.contains("#99FFFFFF"));
        assert!(screen.root.contains("#ff223344"));
        assert!(screen.root.contains("spacing = 16"));
        assert!(screen.root.contains("ScrollView(listOf("));
        assert!(!screen.root.contains("Unsupported component"));
        assert!(
            screen
                .limitations
                .iter()
                .any(|note| note.contains("Animated container"))
        );
        assert!(
            screen
                .limitations
                .iter()
                .any(|note| note.contains("Conditional"))
        );
    }

    #[test]
    fn android_resource_and_click_listener_are_reported() {
        let result = android::translate(
            r#"<LinearLayout xmlns:android="http://schemas.android.com/apk/res/android" android:orientation="vertical">
                <TextView android:text="Headline" />
                <Button android:text="@string/next" android:onClick="next" />
                <EditText android:hint="Name" />
            </LinearLayout>"#,
        ).unwrap();
        assert!(result.root.contains("Text(\"Headline\")"));
        assert!(result.root.contains("enabled = false"));
        assert_eq!(result.actions.len(), 1);
        assert!(
            result
                .limitations
                .iter()
                .any(|message| message.contains("@string/next"))
        );
    }

    #[test]
    fn compose_selection_ignores_other_functions() {
        let result = compose::translate(
            r#"
                import androidx.compose.foundation.layout.Column
                import androidx.compose.material3.Text
                @Composable fun Welcome() { Column { Text(text = "Welcome") } }
                @Composable fun Preview() { Text("Wrong screen") }
            "#,
            "Welcome",
        )
        .unwrap();
        assert!(result.root.contains("Text(\"Welcome\")"));
        assert!(!result.root.contains("Wrong screen"));
    }
}
